SELECT rc.CONSTRAINT_SCHEMA, rc.TABLE_NAME, rc.CONSTRAINT_NAME,
       rc.UPDATE_RULE, rc.DELETE_RULE, rc.MATCH_OPTION
FROM information_schema.REFERENTIAL_CONSTRAINTS AS rc
JOIN information_schema.TABLES AS t
  ON t.TABLE_SCHEMA = rc.CONSTRAINT_SCHEMA AND t.TABLE_NAME = rc.TABLE_NAME
WHERE t.TABLE_TYPE = 'BASE TABLE'
  AND t.TABLE_SCHEMA NOT IN ('information_schema', 'mysql', 'performance_schema', 'sys')
  AND (? IS NULL OR JSON_CONTAINS(?, JSON_QUOTE(t.TABLE_SCHEMA)))
ORDER BY rc.CONSTRAINT_SCHEMA, rc.TABLE_NAME, rc.CONSTRAINT_NAME;
