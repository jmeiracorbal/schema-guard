SELECT s.TABLE_SCHEMA, s.TABLE_NAME, s.INDEX_NAME, s.SEQ_IN_INDEX, s.NON_UNIQUE,
       s.INDEX_TYPE, s.COLUMN_NAME, s.EXPRESSION, s.COLLATION, s.SUB_PART,
       CASE s.IS_VISIBLE WHEN 'YES' THEN 'VISIBLE' WHEN 'NO' THEN 'INVISIBLE' ELSE s.IS_VISIBLE END,
       s.INDEX_COMMENT
FROM information_schema.STATISTICS AS s
JOIN information_schema.TABLES AS t
  ON t.TABLE_SCHEMA = s.TABLE_SCHEMA AND t.TABLE_NAME = s.TABLE_NAME
WHERE t.TABLE_TYPE = 'BASE TABLE'
  AND t.TABLE_SCHEMA NOT IN ('information_schema', 'mysql', 'performance_schema', 'sys')
  AND (? IS NULL OR JSON_CONTAINS(?, JSON_QUOTE(t.TABLE_SCHEMA)))
ORDER BY s.TABLE_SCHEMA, s.TABLE_NAME, s.INDEX_NAME, s.SEQ_IN_INDEX;
