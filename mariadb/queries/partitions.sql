SELECT p.TABLE_SCHEMA, p.TABLE_NAME, p.PARTITION_NAME, p.PARTITION_ORDINAL_POSITION,
       p.PARTITION_METHOD, p.PARTITION_EXPRESSION, p.PARTITION_DESCRIPTION,
       p.SUBPARTITION_NAME, p.SUBPARTITION_ORDINAL_POSITION,
       p.SUBPARTITION_METHOD, p.SUBPARTITION_EXPRESSION
FROM information_schema.PARTITIONS AS p
JOIN information_schema.TABLES AS t
  ON t.TABLE_SCHEMA = p.TABLE_SCHEMA AND t.TABLE_NAME = p.TABLE_NAME
WHERE t.TABLE_TYPE = 'BASE TABLE'
  AND t.TABLE_SCHEMA NOT IN ('information_schema', 'mysql', 'performance_schema', 'sys')
  AND (? IS NULL OR JSON_CONTAINS(?, JSON_QUOTE(t.TABLE_SCHEMA)))
ORDER BY p.TABLE_SCHEMA, p.TABLE_NAME, p.PARTITION_ORDINAL_POSITION, p.SUBPARTITION_ORDINAL_POSITION;
